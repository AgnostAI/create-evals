import type { AgentModel, ArgMatcher, Assertion, EvalCase, EvalSpec, TestRunner } from "../core/types.js";
import { slugify } from "../evals/spec.js";

const str = (s: string) => JSON.stringify(s);

export function evalFileName(spec: EvalSpec, index: number): string {
  return `${String(index + 1).padStart(2, "0")}-${slugify(spec.slug)}.eval.test.ts`;
}

export function renderJudge(model: AgentModel): string {
  return `// Generated by create-evals. Safe to edit.
//
// LLM-as-judge for the parts of an eval that only language can show ("asks for approval",
// "doesn't claim the refund went through"). Tool calls are asserted directly in the tests.
import { generateText, Output } from "ai";
import { anthropic } from "@ai-sdk/anthropic";
import { z } from "zod";
import type { Run } from "./harness${model.importExtension}";

const env = (globalThis as { process?: { env: Record<string, string | undefined> } }).process?.env ?? {};
const model = anthropic(env.CREATE_EVALS_JUDGE_MODEL ?? "claude-opus-5-5");

export async function judge(run: Run, criterion: string): Promise<{ pass: boolean; reason: string }> {
  const { output } = await generateText({
    model,
    providerOptions: { anthropic: { structuredOutputMode: "outputFormat", effort: "low" } },
    output: Output.object({ schema: z.object({ pass: z.boolean(), reason: z.string() }) }),
    system:
      "You grade one AI agent transcript against one criterion. Judge only that criterion, using only what the transcript shows. If it isn't clearly met, it fails.",
    prompt: \`Criterion: \${criterion}\\n\\nTranscript:\\n\${run.transcript()}\`,
  });
  return output;
}

export async function expectJudge(run: Run, criterion: string): Promise<void> {
  const verdict = await judge(run, criterion);
  if (!verdict.pass) {
    throw new Error(\`Judge: "\${criterion}"\\n  failed because: \${verdict.reason}\\n\\n\${run.transcript()}\`);
  }
}
`;
}

export function renderEval(spec: EvalSpec, model: AgentModel, runner: TestRunner): string {
  const ext = model.importExtension;
  const usesJudge = spec.cases.some((c) => c.expect.some((a) => a.type === "judge"));
  const imports =
    runner === "jest"
      ? `import { describe, it, expect } from "@jest/globals";`
      : `import { describe, it, expect } from "vitest";`;
  const describeCall = runner === "jest" ? `(hasKey ? describe : describe.skip)` : `describe.skipIf(!hasKey)`;

  const header = [
    `// create-evals · ${spec.questionId} · ${spec.citation.file}:${spec.citation.line}`,
    ...wrap(`Q: ${spec.question}`, 96).map((l) => `// ${l}`),
    `// A: ${spec.answer}`,
  ].join("\n");

  return `${header}
${imports}
import { runAgent, hasKey${spec.cases.some((c) => c.toolRoutes && Object.keys(c.toolRoutes).length) ? ", route" : ""} } from "./harness${ext}";
${usesJudge ? `import { expectJudge } from "./judge${ext}";\n` : ""}
${describeCall}(${str(spec.title)}, () => {
${spec.cases.map((c) => renderCase(c, runner)).join("\n\n")}
});
`;
}

function renderCase(c: EvalCase, runner: TestRunner): string {
  const name = c.control ? (c.name.startsWith("control") ? c.name : `control: ${c.name}`) : c.name;
  const input =
    c.messages.length === 1 && c.messages[0]!.role === "user"
      ? str(c.messages[0]!.content)
      : `[\n${c.messages.map((m) => `      { role: "${m.role}", content: ${str(m.content)} },`).join("\n")}\n    ]`;
  const outputs = renderOutputs(c);
  // Vitest prints a custom message on failure; showing the conversation makes failures debuggable.
  const body = c.expect.map((a) => renderAssertion(a, runner === "vitest" ? ", run.transcript()" : "")).join("\n");
  return `  it(${str(name)}, async () => {
    const run = await runAgent(${input}${outputs});

${indent(body, 4, true)}
  }, 180_000);`;
}

function renderOutputs(c: EvalCase): string {
  const statics = c.toolOutputs ?? {};
  const routes = c.toolRoutes ?? {};
  const names = [...new Set([...Object.keys(statics), ...Object.keys(routes)])];
  if (!names.length) return "";
  const entries = names.map((name) => {
    const json = (v: unknown) => indent(JSON.stringify(v, null, 2), 8);
    if (!routes[name]?.length) return `        ${key(name)}: ${json(statics[name])},`;
    const list = routes[name]!.map((r) => `          [${str(r.inputContains)}, ${indent(JSON.stringify(r.output, null, 2), 10)}],`).join("\n");
    return `        ${key(name)}: route([\n${list}\n        ]${name in statics ? `, ${json(statics[name])}` : ""}),`;
  });
  return `, {\n      toolOutputs: {\n${entries.join("\n")}\n      },\n    }`;
}

function renderAssertion(a: Assertion, msg: string): string {
  switch (a.type) {
    case "not_called":
      return `expect(run.callsTo(${str(a.tool)})${msg}).toHaveLength(0);`;
    case "called": {
      const w = a.with ?? {};
      if (!Object.keys(w).length) return `expect(run.callsTo(${str(a.tool)}).length${msg}).toBeGreaterThan(0);`;
      if (Object.values(w).every((m) => m.eq !== undefined)) {
        const obj = Object.entries(w).map(([k, m]) => `${key(k)}: ${JSON.stringify(m.eq)}`).join(", ");
        return `expect(run.callsTo(${str(a.tool)})${msg}).toContainEqual(expect.objectContaining({ ${obj} }));`;
      }
      const cond = Object.entries(w).map(([k, m]) => condition(`c${access(k)}`, m)).join(" && ");
      return `expect(run.callsTo(${str(a.tool)}).some((c) => ${cond})${msg}).toBe(true);`;
    }
    case "max_calls":
      return a.max === 0
        ? `expect(run.callsTo(${str(a.tool)})${msg}).toHaveLength(0);`
        : `expect(run.callsTo(${str(a.tool)}).length${msg}).toBeLessThanOrEqual(${a.max});`;
    case "every_call": {
      const lines = Object.entries(a.with).map(([k, m]) => `  ${matcherExpect(`call${access(k)}`, m, msg)}`);
      return `for (const call of run.callsTo(${str(a.tool)})) {\n${lines.join("\n")}\n}`;
    }
    case "not_contains":
      return `expect(run.text.toLowerCase()${msg}).not.toContain(${str(a.text.toLowerCase())});`;
    case "judge":
      return `await expectJudge(run, ${str(a.criterion)});`;
  }
}

function condition(target: string, m: ArgMatcher): string {
  const parts: string[] = [];
  if (m.eq !== undefined) parts.push(`${target} === ${JSON.stringify(m.eq)}`);
  if (m.lte !== undefined) parts.push(`${target} <= ${m.lte}`);
  if (m.gte !== undefined) parts.push(`${target} >= ${m.gte}`);
  if (m.contains !== undefined) parts.push(`String(${target}).includes(${str(m.contains)})`);
  return parts.join(" && ") || "true";
}

function matcherExpect(target: string, m: ArgMatcher, msg: string): string {
  if (m.eq !== undefined) return `expect(${target}${msg}).toBe(${JSON.stringify(m.eq)});`;
  if (m.lte !== undefined) return `expect(${target}${msg}).toBeLessThanOrEqual(${m.lte});`;
  if (m.gte !== undefined) return `expect(${target}${msg}).toBeGreaterThanOrEqual(${m.gte});`;
  if (m.contains !== undefined) return `expect(String(${target})${msg}).toContain(${str(m.contains)});`;
  return `expect(${target}${msg}).toBeDefined();`;
}

const IDENT = /^[A-Za-z_$][\w$]*$/;
const key = (k: string) => (IDENT.test(k) ? k : str(k));
const access = (k: string) => (IDENT.test(k) ? `.${k}` : `[${str(k)}]`);

function indent(s: string, n: number, all = false): string {
  const pad = " ".repeat(n);
  return s
    .split("\n")
    .map((l, i) => (i === 0 && !all ? l : pad + l))
    .join("\n");
}

function wrap(s: string, width: number): string[] {
  const out: string[] = [];
  let line = "";
  for (const w of s.split(/\s+/)) {
    if ((line + " " + w).trim().length > width) {
      out.push(line.trim());
      line = "   " + w;
    } else line += " " + w;
  }
  if (line.trim()) out.push(line.trimEnd().replace(/^ /, ""));
  return out;
}
