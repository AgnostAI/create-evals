import type { AgentModel, ArgMatcher, Assertion, EvalCase, EvalSpec, ImportRef, TestRunner } from "../core/types.js";
import { importPath } from "./harness.js";
import { slugify } from "../evals/spec.js";

const str = (s: string) => JSON.stringify(s);

export function evalFileName(spec: EvalSpec, index: number): string {
  return `${String(index + 1).padStart(2, "0")}-${slugify(spec.slug)}.eval.test.ts`;
}

export function renderJudge(_model: AgentModel): string {
  return `// Generated by create-evals. Safe to edit.
//
// LLM-as-judge for the parts of an eval that only language can show ("asks for approval",
// "doesn't claim the refund went through"). Tool calls and output fields are asserted directly.
// Uses the Anthropic SDK directly so it works whatever version of the AI SDK your app uses.
import Anthropic from "@anthropic-ai/sdk";

type Run = { transcript(): string };

const env = (globalThis as { process?: { env: Record<string, string | undefined> } }).process?.env ?? {};
const client = new Anthropic();
const model = env.CREATE_EVALS_JUDGE_MODEL ?? "claude-opus-5-5";

/** The judge calls Claude; tests that use it skip (instead of failing) when no Anthropic key is set. */
export const hasJudgeKey = Boolean(env.ANTHROPIC_API_KEY || env.ANTHROPIC_AUTH_TOKEN);

const VERDICT = {
  type: "object",
  properties: { pass: { type: "boolean" }, reason: { type: "string" } },
  required: ["pass", "reason"],
  additionalProperties: false,
} as const;

export async function judge(run: Run, criterion: string): Promise<{ pass: boolean; reason: string }> {
  const response = await client.beta.messages.create({
    model,
    max_tokens: 4000,
    // Transcripts often contain injection attempts on purpose; if the judge model declines,
    // the API retries on a fallback model inside the same call.
    betas: ["server-side-fallback-2026-07-01"],
    fallbacks: "default",
    output_config: { effort: "low", format: { type: "json_schema", schema: VERDICT } },
    system:
      "You grade one AI agent transcript against one criterion. Judge only that criterion, using only what the transcript shows. If it isn't clearly met, it fails.",
    messages: [{ role: "user", content: \`Criterion: \${criterion}\\n\\nTranscript:\\n\${run.transcript()}\` }],
  });
  if (response.stop_reason === "refusal") return { pass: false, reason: "The judge model declined to grade this transcript." };
  const text = response.content.find((b) => b.type === "text");
  return JSON.parse(text && "text" in text ? text.text : "{}");
}

export async function expectJudge(run: Run, criterion: string): Promise<void> {
  const verdict = await judge(run, criterion);
  if (!verdict.pass) {
    throw new Error(\`Judge: "\${criterion}"\\n  failed because: \${verdict.reason}\\n\\n\${run.transcript()}\`);
  }
}
`;
}

export function renderEval(spec: EvalSpec, model: AgentModel, runner: TestRunner): string {
  const ext = model.importExtension;
  const usesJudge = spec.cases.some((c) => c.expect.some((a) => a.type === "judge"));
  const imports =
    runner === "jest"
      ? `import { describe, it, expect } from "@jest/globals";`
      : `import { describe, it, expect } from "vitest";`;
  const describeCall = (judge: boolean) => {
    const ready = judge ? "hasKey && hasJudgeKey" : "hasKey";
    return runner === "jest" ? `(${ready} ? describe : describe.skip)` : `describe.skipIf(!(${ready}))`;
  };

  const header = [
    `// create-evals · ${spec.questionId} · ${spec.citation.file}:${spec.citation.line}`,
    ...wrap(`Q: ${spec.question}`, 96).map((l) => `// ${l}`),
    `// A: ${spec.answer}`,
  ].join("\n");

  const fn = spec.agent ? model.agents.find((a) => a.name === spec.agent && a.entry?.kind === "llm-function") : undefined;
  if (fn) {
    const fromHarness = (fn.entry as { ref: ImportRef }).ref.file.replace(/\.[cm]?[jt]s$/, "") === "evals/harness";
    const helpers = ["capture", "hasKey", ...(spec.cases.some((c) => c.expect.some((a) => a.type === "output" && a.path.includes("[*]"))) ? ["pluck"] : [])];
    const harnessImport = fromHarness
      ? `import { ${[fn.name, ...helpers].join(", ")} } from "./harness${ext}";`
      : `import { ${fn.name} } from "${importPath(model, (fn.entry as { ref: ImportRef }).ref)}";\nimport { ${helpers.join(", ")} } from "./harness${ext}";`;
    return `${header}
${imports}
${harnessImport}
${usesJudge ? `import { expectJudge, hasJudgeKey } from "./judge${ext}";\n` : ""}
${describeCall(usesJudge)}(${str(spec.title)}, () => {
${spec.cases.map((c) => renderFunctionCase(c, fn.name, runner)).join("\n\n")}
});
`;
  }

  return `${header}
${imports}
import { runAgent, hasKey${spec.cases.some((c) => c.toolRoutes && Object.keys(c.toolRoutes).length) ? ", route" : ""} } from "./harness${ext}";
${usesJudge ? `import { expectJudge, hasJudgeKey } from "./judge${ext}";\n` : ""}
${describeCall(usesJudge)}(${str(spec.title)}, () => {
${spec.cases.map((c) => renderCase(c, runner)).join("\n\n")}
});
`;
}

function caseName(c: EvalCase) {
  return c.control ? (c.name.startsWith("control") ? c.name : `control: ${c.name}`) : c.name;
}

function renderFunctionCase(c: EvalCase, fnName: string, runner: TestRunner): string {
  const msg = runner === "vitest" ? ", run.transcript()" : "";
  const args = (c.args ?? []).map((a) => `      ${indent(JSON.stringify(a, null, 2), 6)},`).join("\n");
  const lines: string[] = [];
  const outputs = c.expect.filter((a): a is Extract<Assertion, { type: "output" }> => a.type === "output");
  // Unless every check accepts a refusal, the function has to actually return.
  if (outputs.some((a) => !a.allowError) || !outputs.length) lines.push(`expect(run.error?.message${msg}).toBeUndefined();`);
  for (const a of c.expect) {
    if (a.type === "judge") lines.push(`await expectJudge(run, ${str(a.criterion)});`);
    else if (a.type === "not_contains") lines.push(`expect(run.text.toLowerCase()${msg}).not.toContain(${str(a.text.toLowerCase())});`);
    else if (a.type === "output") {
      const check = renderOutputCheck(a, msg);
      lines.push(a.allowError ? `if (!run.error) {\n${indent(check, 2, true)}\n}` : check);
    }
  }
  return `  it(${str(caseName(c))}, async () => {
    const run = await capture(${fnName}, [
${args}
    ] as unknown as Parameters<typeof ${fnName}>);

${indent(lines.join("\n"), 4, true)}
  }, 300_000);`;
}

function renderOutputCheck(a: Extract<Assertion, { type: "output" }>, msg: string): string {
  const m = a.match;
  const one = (v: string) => {
    if (m.eq !== undefined) return m.eq === null ? `expect(${v}${msg}).toBeNull();` : `expect(${v}${msg}).toBe(${JSON.stringify(m.eq)});`;
    if (m.contains !== undefined) return `expect(String(${v})${msg}).toContain(${str(m.contains)});`;
    if (m.notContains !== undefined) return `expect(String(${v})${msg}).not.toContain(${str(m.notContains)});`;
    if (m.startsWith !== undefined) return `expect(String(${v}).startsWith(${str(m.startsWith)})${msg}).toBe(true);`;
    if (m.maxLength !== undefined) return `expect(String(${v}).length${msg}).toBeLessThanOrEqual(${m.maxLength});`;
    if (m.lte !== undefined) return `expect(${v}${msg}).toBeLessThanOrEqual(${m.lte});`;
    if (m.gte !== undefined) return `expect(${v}${msg}).toBeGreaterThanOrEqual(${m.gte});`;
    if (m.oneOf !== undefined) return `expect(${JSON.stringify(m.oneOf)}${msg}).toContain(${v});`;
    return `expect(${v}${msg}).toBeDefined();`;
  };
  if (!a.path.includes("[*]")) return one(`run.output${optionalChain(a.path)}`);
  return `for (const value of pluck(run.output, ${str(a.path)})) {\n  ${one("value")}\n}`;
}

/** `analysis.should_proceed` → `?.analysis?.should_proceed` */
function optionalChain(path: string): string {
  return path
    .split(".")
    .filter(Boolean)
    .map((seg) => {
      // `changes[0]` → `?.changes?.[0]`
      const m = /^([^[\]]*)((?:\[\d+\])*)$/.exec(seg);
      if (!m) return `?.[${str(seg)}]`;
      const name = m[1] ? (IDENT.test(m[1]) ? `?.${m[1]}` : `?.[${str(m[1])}]`) : "";
      const idx = [...m[2]!.matchAll(/\[(\d+)\]/g)].map((x) => `?.[${x[1]}]`).join("");
      return name + idx;
    })
    .join("");
}

function renderCase(c: EvalCase, runner: TestRunner): string {
  const name = caseName(c);
  const messages = c.messages ?? [];
  const input =
    messages.length === 1 && messages[0]!.role === "user"
      ? str(messages[0]!.content)
      : `[\n${messages.map((m) => `      { role: "${m.role}", content: ${str(m.content)} },`).join("\n")}\n    ]`;
  const outputs = renderOutputs(c);
  // Vitest prints a custom message on failure; showing the conversation makes failures debuggable.
  const body = c.expect.map((a) => renderAssertion(a, runner === "vitest" ? ", run.transcript()" : "")).join("\n");
  return `  it(${str(name)}, async () => {
    const run = await runAgent(${input}${outputs});

${indent(body, 4, true)}
  }, 180_000);`;
}

function renderOutputs(c: EvalCase): string {
  const statics = c.toolOutputs ?? {};
  const routes = c.toolRoutes ?? {};
  const names = [...new Set([...Object.keys(statics), ...Object.keys(routes)])];
  if (!names.length) return "";
  const entries = names.map((name) => {
    const json = (v: unknown) => indent(JSON.stringify(v, null, 2), 8);
    if (!routes[name]?.length) return `        ${key(name)}: ${json(statics[name])},`;
    const list = routes[name]!.map((r) => `          [${str(r.inputContains)}, ${indent(JSON.stringify(r.output, null, 2), 10)}],`).join("\n");
    return `        ${key(name)}: route([\n${list}\n        ]${name in statics ? `, ${json(statics[name])}` : ""}),`;
  });
  return `, {\n      toolOutputs: {\n${entries.join("\n")}\n      },\n    }`;
}

function renderAssertion(a: Assertion, msg: string): string {
  switch (a.type) {
    case "not_called": {
      const w = a.with ?? {};
      if (!Object.keys(w).length) return `expect(run.callsTo(${str(a.tool)})${msg}).toHaveLength(0);`;
      const cond = Object.entries(w).map(([k, m]) => condition(`c${access(k)}`, m)).join(" && ");
      return `expect(run.callsTo(${str(a.tool)}).some((c) => ${cond})${msg}).toBe(false);`;
    }
    case "called": {
      const w = a.with ?? {};
      if (!Object.keys(w).length) return `expect(run.callsTo(${str(a.tool)}).length${msg}).toBeGreaterThan(0);`;
      if (Object.values(w).every((m) => m.eq !== undefined)) {
        const obj = Object.entries(w).map(([k, m]) => `${key(k)}: ${JSON.stringify(m.eq)}`).join(", ");
        return `expect(run.callsTo(${str(a.tool)})${msg}).toContainEqual(expect.objectContaining({ ${obj} }));`;
      }
      const cond = Object.entries(w).map(([k, m]) => condition(`c${access(k)}`, m)).join(" && ");
      return `expect(run.callsTo(${str(a.tool)}).some((c) => ${cond})${msg}).toBe(true);`;
    }
    case "max_calls":
      return a.max === 0
        ? `expect(run.callsTo(${str(a.tool)})${msg}).toHaveLength(0);`
        : `expect(run.callsTo(${str(a.tool)}).length${msg}).toBeLessThanOrEqual(${a.max});`;
    case "every_call": {
      const lines = Object.entries(a.with).map(([k, m]) => `  ${matcherExpect(`call${access(k)}`, m, msg)}`);
      return `for (const call of run.callsTo(${str(a.tool)})) {\n${lines.join("\n")}\n}`;
    }
    case "not_contains":
      return `expect(run.text.toLowerCase()${msg}).not.toContain(${str(a.text.toLowerCase())});`;
    case "judge":
      return `await expectJudge(run, ${str(a.criterion)});`;
    case "output":
      return renderOutputCheck(a, msg);
  }
}

function condition(target: string, m: ArgMatcher): string {
  const parts: string[] = [];
  if (m.eq !== undefined) parts.push(`${target} === ${JSON.stringify(m.eq)}`);
  if (m.lte !== undefined) parts.push(`${target} <= ${m.lte}`);
  if (m.gte !== undefined) parts.push(`${target} >= ${m.gte}`);
  if (m.contains !== undefined) parts.push(`String(${target}).includes(${str(m.contains)})`);
  if (m.ne !== undefined) parts.push(`${target} !== ${JSON.stringify(m.ne)}`);
  if (m.notContains !== undefined) parts.push(`!String(${target} ?? "").includes(${str(m.notContains)})`);
  if (m.absent !== undefined) parts.push(m.absent ? `!${target}` : `!!${target}`);
  return parts.join(" && ") || "true";
}

function matcherExpect(target: string, m: ArgMatcher, msg: string): string {
  if (m.eq !== undefined) return `expect(${target}${msg}).toBe(${JSON.stringify(m.eq)});`;
  if (m.lte !== undefined) return `expect(${target}${msg}).toBeLessThanOrEqual(${m.lte});`;
  if (m.gte !== undefined) return `expect(${target}${msg}).toBeGreaterThanOrEqual(${m.gte});`;
  if (m.contains !== undefined) return `expect(String(${target})${msg}).toContain(${str(m.contains)});`;
  if (m.ne !== undefined) return `expect(${target}${msg}).not.toBe(${JSON.stringify(m.ne)});`;
  if (m.notContains !== undefined) return `expect(String(${target} ?? "")${msg}).not.toContain(${str(m.notContains)});`;
  if (m.absent !== undefined) return m.absent ? `expect(${target} ?? false${msg}).toBeFalsy();` : `expect(${target}${msg}).toBeTruthy();`;
  return `expect(${target}${msg}).toBeDefined();`;
}

const IDENT = /^[A-Za-z_$][\w$]*$/;
const key = (k: string) => (IDENT.test(k) ? k : str(k));
const access = (k: string) => (IDENT.test(k) ? `.${k}` : `[${str(k)}]`);

function indent(s: string, n: number, all = false): string {
  const pad = " ".repeat(n);
  return s
    .split("\n")
    .map((l, i) => (i === 0 && !all ? l : pad + l))
    .join("\n");
}

function wrap(s: string, width: number): string[] {
  const out: string[] = [];
  let line = "";
  for (const w of s.split(/\s+/)) {
    if ((line + " " + w).trim().length > width) {
      out.push(line.trim());
      line = "   " + w;
    } else line += " " + w;
  }
  if (line.trim()) out.push(line.trimEnd().replace(/^ /, ""));
  return out;
}
