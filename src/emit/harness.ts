import path from "node:path";
import type { AgentDef, AgentModel, ImportRef } from "../core/types.js";

export class HarnessError extends Error {}

/** Import specifier from evals/harness.ts to a repo file, honoring the repo's extension style. */
export function importPath(model: AgentModel, ref: ImportRef, fromDir = "evals"): string {
  const noExt = ref.file.replace(/\.(ts|tsx|mts|cts|js|mjs)$/, "");
  let rel = path.posix.relative(fromDir, noExt);
  if (!rel.startsWith(".")) rel = `./${rel}`;
  return rel + model.importExtension;
}

const HEADER = `// Generated by create-evals. Safe to edit — re-running create-evals won't overwrite it.
//
// Runs your agent with every tool swapped for a recorder, so evals never refund, delete,
// send, or execute anything for real. Each test scripts what tools return via \`toolOutputs\`.`;

const SHARED = `export type Message = { role: "user" | "assistant"; content: string };
export type ToolCall = { tool: string; input: Record<string, any> };
export type ToolOutputs = Record<string, unknown | ((input: any) => unknown)>;

export interface Run {
  /** The agent's final reply. */
  text: string;
  /** Every tool call, in order. */
  calls: ToolCall[];
  /** Inputs of every call to one tool. */
  callsTo(tool: string): Record<string, any>[];
  /** Readable transcript for the judge and for failure messages. */
  transcript(): string;
}

// Read env without depending on @types/node being loaded.
const env = ((globalThis as { process?: { env: Record<string, string | undefined> } }).process?.env ?? {}) as Record<string, string | undefined>;

/** What a tool returns when a test doesn't script it. */
const DEFAULT_OUTPUT = { ok: true };

/** Tools that run for real during evals. Empty by default; add read-only tools if you want. */
const PASSTHROUGH = new Set<string>([]);

function outputFor(tool: string, input: unknown, outputs: ToolOutputs) {
  if (!(tool in outputs)) return DEFAULT_OUTPUT;
  const out = outputs[tool];
  return typeof out === "function" ? (out as (i: unknown) => unknown)(input) : out;
}

/** Input-dependent tool output: the first route whose text appears in the call's input wins. */
export function route(routes: [inputContains: string, output: unknown][], fallback: unknown = DEFAULT_OUTPUT) {
  return (input: unknown) => {
    const haystack = typeof input === "string" ? input : JSON.stringify(input);
    return routes.find(([needle]) => haystack.includes(needle))?.[1] ?? fallback;
  };
}

/** A run that hits the agent's own turn/step limit is a result worth asserting on, not a crash. */
function stoppedEarly(err: unknown): string | undefined {
  const e = err as Error;
  return /max.?turns|max.?steps|step.?limit|turn.?limit/i.test(\`\${e?.name} \${e?.message}\`) ? \`[agent stopped: \${e.message}]\` : undefined;
}

function toMessages(input: string | Message[]): Message[] {
  return typeof input === "string" ? [{ role: "user", content: input }] : input;
}

function makeRun(messages: Message[], text: string, calls: ToolCall[]): Run {
  return {
    text,
    calls,
    callsTo: (tool) => calls.filter((c) => c.tool === tool).map((c) => c.input),
    transcript: () =>
      [
        ...messages.map((m) => \`\${m.role.toUpperCase()}: \${m.content}\`),
        ...calls.map((c) => \`TOOL CALL \${c.tool}(\${JSON.stringify(c.input)})\`),
        \`ASSISTANT (final): \${text}\`,
      ].join("\\n"),
  };
}`;

export function renderHarness(model: AgentModel): string {
  const agent = pickAgent(model);
  const entry = agent.entry!;
  const keyCheck = `/** Evals call your real model. Without a key they're skipped instead of failing. */
export const hasKey = Boolean(env.${model.providerEnv});
if (!hasKey) console.warn("[create-evals] ${model.providerEnv} is not set; skipping evals.");`;

  switch (entry.kind) {
    case "function": {
      if (!agent.toolsRef) {
        throw new HarnessError(
          `${entry.ref.exportName} builds its tools inline, so the harness can't swap them for recorders. Export the tools object (e.g. \`export const tools = {...}\`) and re-run.`,
        );
      }
      const call = entry.input === "messages" ? "messages" : 'messages.filter((m) => m.role === "user").at(-1)!.content';
      const read = entry.returns === "text" ? "String(result)" : "String((result as any)?.text ?? result)";
      return `${HEADER}
import { ${entry.ref.exportName} } from "${importPath(model, entry.ref)}";
import { ${agent.toolsRef.exportName} as tools } from "${importPath(model, agent.toolsRef)}";

${SHARED}

${keyCheck}

export async function runAgent(input: string | Message[], opts: { toolOutputs?: ToolOutputs } = {}): Promise<Run> {
  const messages = toMessages(input);
  const calls: ToolCall[] = [];
  const restore = patchTools(calls, opts.toolOutputs ?? {});
  try {
    const result = await ${entry.ref.exportName}(${call} as any);
    return makeRun(messages, ${read}, calls);
  } catch (err) {
    const stopped = stoppedEarly(err);
    if (stopped) return makeRun(messages, stopped, calls);
    throw err;
  } finally {
    restore();
  }
}

function patchTools(calls: ToolCall[], outputs: ToolOutputs) {
  const originals = new Map<string, any>();
  for (const [name, tool] of Object.entries(tools as Record<string, any>)) {
    if (typeof tool?.execute !== "function") continue;
    const original = tool.execute;
    originals.set(name, original);
    tool.execute = async (input: any, ...rest: any[]) => {
      calls.push({ tool: name, input });
      return PASSTHROUGH.has(name) ? original(input, ...rest) : outputFor(name, input, outputs);
    };
  }
  return () => {
    for (const [name, original] of originals) (tools as Record<string, any>)[name].execute = original;
  };
}
`;
    }

    case "vercel-agent":
    case "mastra-agent": {
      const isMastra = entry.kind === "mastra-agent";
      const name = entry.ref.exportName;
      return `${HEADER}
import { ${name} } from "${importPath(model, entry.ref)}";

${SHARED}

${keyCheck}

export async function runAgent(input: string | Message[], opts: { toolOutputs?: ToolOutputs } = {}): Promise<Run> {
  const messages = toMessages(input);
  const calls: ToolCall[] = [];
  const restore = await patchTools(calls, opts.toolOutputs ?? {});
  try {
    const result = await ${name}.generate(${isMastra ? "messages as any" : "{ messages } as any"});
    return makeRun(messages, result.text, calls);
  } catch (err) {
    const stopped = stoppedEarly(err);
    if (stopped) return makeRun(messages, stopped, calls);
    throw err;
  } finally {
    restore();
  }
}

async function patchTools(calls: ToolCall[], outputs: ToolOutputs) {
  const tools = (${isMastra ? `await ${name}.listTools()` : `${name}.tools`}) as Record<string, any>;
  const originals = new Map<string, any>();
  for (const [name, tool] of Object.entries(tools)) {
    if (typeof tool?.execute !== "function") continue;
    const original = tool.execute;
    originals.set(name, original);
    tool.execute = async (input: any, ...rest: any[]) => {
      calls.push({ tool: name, input });
      return PASSTHROUGH.has(name) ? original(input, ...rest) : outputFor(name, input, outputs);
    };
  }
  return () => {
    for (const [name, original] of originals) tools[name].execute = original;
  };
}
`;
    }

    case "openai-agent": {
      const name = entry.ref.exportName;
      return `${HEADER}
import { run, setTracingDisabled, user, assistant } from "@openai/agents";
import { ${name} } from "${importPath(model, entry.ref)}";

setTracingDisabled(true);

${SHARED}

${keyCheck}

export async function runAgent(input: string | Message[], opts: { toolOutputs?: ToolOutputs } = {}): Promise<Run> {
  const messages = toMessages(input);
  const calls: ToolCall[] = [];
  const restore = patchTools(calls, opts.toolOutputs ?? {});
  try {
    const items = messages.map((m) => (m.role === "user" ? user(m.content) : assistant(m.content)));
    // Recorded tools make agents double-check more than usual; give them room before calling it a loop.
    const result = await run(${name}, messages.length === 1 ? messages[0]!.content : items, { maxTurns: 20 });
    const paused = result.interruptions?.map((i: any) => i.rawItem?.name ?? "tool") ?? [];
    const text = String(result.finalOutput ?? (paused.length ? \`[paused for human approval: \${paused.join(", ")}]\` : ""));
    return makeRun(messages, text, calls);
  } catch (err) {
    const stopped = stoppedEarly(err);
    if (stopped) return makeRun(messages, stopped, calls);
    throw err;
  } finally {
    restore();
  }
}

function patchTools(calls: ToolCall[], outputs: ToolOutputs) {
  const originals = new Map<any, any>();
  for (const tool of ${name}.tools as any[]) {
    if (tool.type !== "function") continue;
    const original = tool.invoke;
    originals.set(tool, original);
    tool.invoke = async (ctx: any, raw: string, ...rest: any[]) => {
      let input: any = raw;
      try {
        input = JSON.parse(raw);
      } catch {}
      calls.push({ tool: tool.name, input });
      if (PASSTHROUGH.has(tool.name)) return original.call(tool, ctx, raw, ...rest);
      const out = outputFor(tool.name, input, outputs);
      return typeof out === "string" ? out : JSON.stringify(out);
    };
  }
  return () => {
    for (const [tool, original] of originals) tool.invoke = original;
  };
}
`;
    }
  }
}

export function pickAgent(model: AgentModel): AgentDef {
  const withEntry = model.agents.filter((a) => a.entry);
  const best = withEntry.sort((a, b) => b.toolNames.length - a.toolNames.length)[0];
  if (!best) {
    throw new HarnessError(
      "Couldn't find an exported agent to run. Export your agent (or the function that calls generateText) so the evals can import it.",
    );
  }
  return best;
}
