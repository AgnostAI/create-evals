import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import type { AgentModel, ImportRef } from "../core/types.js";
import { importPath } from "../emit/harness.js";
import type { Example, ProbeRun } from "./index.js";

// Runs the real agent once per example through evals/harness.ts (tools recorded, not executed),
// so the developer sees what their agent actually does before picking what it should do.

const DIR = ".create-evals";

export function renderProbe(model: AgentModel, examples: Example[]): string {
  const ext = model.importExtension;
  const fnNames = [...new Set(examples.map((e) => e.agent).filter((a): a is string => !!a))];
  const fnImports = fnNames.map((name) => {
    const def = model.agents.find((a) => a.name === name && a.entry?.kind === "llm-function");
    const ref = (def?.entry as { ref: ImportRef } | undefined)?.ref;
    if (!ref || ref.file.replace(/\.[cm]?[jt]s$/, "") === "evals/harness") return `import { ${name} } from "../evals/harness${ext}";`;
    return `import { ${name} } from "${importPath(model, ref, DIR)}";`;
  });
  const conversational = examples.some((e) => !e.agent);
  const harness = [conversational ? "runAgent, route" : "", fnNames.length ? "capture" : ""].filter(Boolean).join(", ");
  const inputs = examples.map((e) => ({ id: e.id, agent: e.agent, messages: e.messages, args: e.args, toolOutputs: e.toolOutputs, toolRoutes: e.toolRoutes }));
  return `// Generated by create-evals probe; safe to delete. Runs each example once against your real agent.
import { writeFileSync } from "node:fs";
import { ${harness} } from "../evals/harness${ext}";
${fnImports.join("\n")}

const examples: any[] = ${JSON.stringify(inputs, null, 2)};
const fns: Record<string, any> = { ${fnNames.join(", ")} };
const results: any[] = [];

// One at a time: the harness swaps tools in place, so runs can't overlap.
for (const [i, ex] of examples.entries()) {
  console.log(\`[\${i + 1}/\${examples.length}] \${ex.id}\`);
  try {
    if (ex.agent) {
      const run = await capture(fns[ex.agent], ex.args ?? []);
      results.push({ id: ex.id, output: run.output, text: run.text, error: run.error?.message, transcript: run.transcript() });
    } else {
      const toolOutputs: Record<string, unknown> = { ...(ex.toolOutputs ?? {}) };
      for (const [tool, routes] of Object.entries((ex.toolRoutes ?? {}) as Record<string, { inputContains: string; output: unknown }[]>)) {
        toolOutputs[tool] = route(routes.map((r) => [r.inputContains, r.output]), ex.toolOutputs?.[tool] ?? { ok: true });
      }
      const run = await runAgent(ex.messages, { toolOutputs });
      results.push({ id: ex.id, text: run.text, calls: run.calls, transcript: run.transcript() });
    }
  } catch (err: any) {
    results.push({ id: ex.id, error: String(err?.message ?? err) });
  }
}
writeFileSync(new URL("./probe-raw.json", import.meta.url), JSON.stringify(results, null, 2));
`;
}

export class ProbeError extends Error {}

export function runProbe(model: AgentModel, examples: Example[], onLine: (line: string) => void = () => {}): ProbeRun[] {
  const root = model.root;
  if (!existsSync(path.join(root, "evals", "harness.ts"))) throw new ProbeError("No evals/harness.ts yet. Run `create-evals harness` first.");
  const harness = readFileSync(path.join(root, "evals", "harness.ts"), "utf8");
  if (harness.includes("create-evals: wire up")) throw new ProbeError("evals/harness.ts isn't wired yet: implement callYourAgent() first.");
  mkdirSync(path.join(root, DIR), { recursive: true });
  const script = path.join(root, DIR, "probe.ts");
  const out = path.join(root, DIR, "probe-raw.json");
  writeFileSync(script, renderProbe(model, examples));
  if (existsSync(out)) writeFileSync(out, "[]");

  const local = path.join(root, "node_modules", ".bin", "tsx");
  const [bin, args] = existsSync(local) ? [local, [script]] : ["npx", ["-y", "tsx", script]];
  const res = spawnSync(bin, args, { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"], maxBuffer: 64 * 1024 * 1024 });
  for (const line of (res.stdout ?? "").split("\n")) if (/^\[\d+\/\d+\]/.test(line)) onLine(line);
  const runs = existsSync(out) ? (JSON.parse(readFileSync(out, "utf8")) as ProbeRun[]) : [];
  if (res.status !== 0 || runs.length < examples.length) {
    const err = (res.stderr || res.stdout || "").split("\n").filter((l) => l.trim() && !/^\s+at /.test(l)).slice(0, 12).join("\n");
    throw new ProbeError(`The probe script failed (${path.relative(root, script)}):\n${err}`);
  }
  return runs;
}
